const MESSAGES: Record<Locale, Record<MessageKey, string>> = {
  fr: FR_MESSAGES,
  en: EN_MESSAGES,
};

export type TranslationVariables = Record<string, string | number>;

export function normalizeLocale(value: unknown): Locale {
  return value === "en" ? "en" : DEFAULT_LOCALE;
}

export function formatLocale(locale: Locale): string {
  return locale === "en" ? "en-GB" : "fr-FR";
}

export function t(
  locale: Locale,
  key: MessageKey,
  variables: TranslationVariables = {},
): string {
  return MESSAGES[locale][key].replace(/\{(\w+)\}/g, (match, name: string) =>
    name in variables ? String(variables[name]) : match,
  );
}

export function plural(
  locale: Locale,
  keys: { one: MessageKey; other: MessageKey },
  count: number,
  variables: TranslationVariables = {},
): string {
  return t(locale, count === 1 ? keys.one : keys.other, { ...variables, count });
}
